// Writes the site's /api page from the repository's generated API.md.
//
// API.md is written by jsii-docgen at post-compile and lives at the repository
// root, where the README and the guides link to it. Publishing it here means a
// reader — or a model reading llms-full.txt — gets the guides and the full API
// surface from one site.
//
// Why a generated copy rather than a symlink into the content collection, the
// other approach the plan allowed: Starlight requires a title, and the
// collection (see ../src/content.config.ts) supplies a missing one from the
// file's first level-one heading. API.md's first heading is
// `# API Reference <a name="API Reference" id="api-reference"></a>` — every
// heading jsii-docgen writes carries a raw anchor — so the derived title
// rendered that markup as the page title and the browser tab. API.md is
// generated and must not be hand-edited to add frontmatter, so the frontmatter
// is prepended here instead.
//
// This runs as site/package.json's `prebuild`, so `pnpm --dir site build`
// cannot publish a stale reference: the page is rewritten from API.md on every
// build. The output is gitignored (declared in .projenrc.ts) — it is a copy of
// a generated file, and the one copy that is tracked is API.md itself.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const source = fileURLToPath(new URL('../../API.md', import.meta.url));
const target = fileURLToPath(
  new URL('../src/content/docs/api.md', import.meta.url),
);

const frontmatter = [
  '---',
  '# GENERATED FILE — written by site/scripts/generate-api-page.mjs from the',
  '# repository root API.md on every build. Edits here are lost.',
  'title: API reference',
  'description: >-',
  '  Every construct, property, and default in cdk-github-microvm-runners,',
  '  generated from the source.',
  '---',
  '',
].join('\n');

let api;
try {
  api = await readFile(source, 'utf8');
} catch (error) {
  throw new Error(
    `Cannot read ${source}. It is generated by jsii-docgen at post-compile and is tracked in the repository; run \`just compile\` if it is missing.`,
    { cause: error },
  );
}

await writeFile(target, `${frontmatter}${api}`);
